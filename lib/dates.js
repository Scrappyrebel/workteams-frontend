// Date helpers — always use the device's LOCAL timezone, never UTC.
// new Date().toISOString() is UTC: after 7pm CT it returns tomorrow's date,
// which hid same-day shifts from Schedule/Dashboard and blocked clock-ins.
export function localToday() {
  const d = new Date();
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, "0");
  const day = String(d.getDate()).padStart(2, "0");
  return `${y}-${m}-${day}`;
}

// "YYYY-MM-DD" for N days ago, local timezone.
export function localDaysAgo(n) {
  const d = new Date();
  d.setDate(d.getDate() - n);
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, "0");
  const day = String(d.getDate()).padStart(2, "0");
  return `${y}-${m}-${day}`;
}
